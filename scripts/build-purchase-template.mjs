// Builds the purchase-order template the app fills in, from a real Bobcat Racing purchase workbook.
//
//   node scripts/build-purchase-template.mjs "<path to the source .xlsx>"
//
// The source file is only READ. From it this keeps sheet "Sheet1", the header row and ONE clean
// body row (as the style pattern), and removes everything else: the purchase data, hyperlinks,
// printer settings, and SharePoint / author metadata (this repository is public). Header cells are
// normalised to the first header cell's style, since the source's header styles drifted from
// copy-and-paste. Output:
//   assets/purchase-order-template.xlsx           the cleaned workbook (the visible source of truth)
//   lib/purchaseSheet/templateData.ts             the same file embedded as base64, so it ships with the
//                                                 app with no file-tracing configuration
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ExcelJS from 'exceljs'

const source = process.argv[2]
if (!source) {
  console.error('Usage: node scripts/build-purchase-template.mjs "<path to source .xlsx>"')
  process.exit(1)
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex')
const before = sha(source)

const wb = new ExcelJS.Workbook()
await wb.xlsx.readFile(source)
const ws = wb.worksheets[0]
if (ws.name !== 'Sheet1') throw new Error(`Expected the first sheet to be "Sheet1", found "${ws.name}"`)

const headers = []
for (let c = 1; c <= ws.columnCount; c++) headers.push(String(ws.getCell(1, c).value ?? ''))
console.log('Source headers:', headers.join(' | '))

// Row 3 is the first data row without the first-row border quirk; keep it as the style pattern.
const sample = ws.getRow(3)
const patterns = []
for (let c = 1; c <= ws.columnCount; c++) patterns.push(JSON.parse(JSON.stringify(sample.getCell(c).style)))
const headerStyle = JSON.parse(JSON.stringify(ws.getCell('A1').style))
const widths = []
for (let c = 1; c <= ws.columnCount; c++) widths.push(ws.getColumn(c).width)

// Rebuild a clean sheet rather than splicing rows (keeps stray hyperlinks/metadata out).
const clean = new ExcelJS.Workbook()
clean.creator = 'Bobcat Racing Dashboard'
clean.lastModifiedBy = 'Bobcat Racing Dashboard'
clean.title = 'Bobcat Racing purchase order template'
clean.created = new Date('2026-01-01T00:00:00Z')
clean.modified = new Date('2026-01-01T00:00:00Z')
const out = clean.addWorksheet('Sheet1', { views: [{ state: 'normal' }] })
out.properties.defaultRowHeight = 15.75
headers.forEach((h, i) => {
  const cell = out.getCell(1, i + 1)
  cell.value = h
  cell.style = headerStyle
  out.getColumn(i + 1).width = widths[i]
  out.getCell(2, i + 1).style = patterns[i]
})
out.getRow(1).height = 15.75
out.getRow(2).height = 15.75

mkdirSync(resolve(root, 'assets'), { recursive: true })
mkdirSync(resolve(root, 'lib/purchaseSheet'), { recursive: true })
const xlsxPath = resolve(root, 'assets/purchase-order-template.xlsx')
await clean.xlsx.writeFile(xlsxPath)

const b64 = readFileSync(xlsxPath).toString('base64')
writeFileSync(
  resolve(root, 'lib/purchaseSheet/templateData.ts'),
  `// GENERATED by scripts/build-purchase-template.mjs from assets/purchase-order-template.xlsx. Do not edit by hand.\n` +
    `export const PURCHASE_TEMPLATE_BASE64 =\n  '${b64}'\n`
)

const after = sha(source)
console.log(`Wrote assets/purchase-order-template.xlsx (${readFileSync(xlsxPath).length} bytes) and lib/purchaseSheet/templateData.ts`)
console.log(`Source file unchanged: ${before === after} (sha256 ${before.slice(0, 16)}…)`)
